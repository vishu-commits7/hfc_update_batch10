/* ------------------------------------------------------------------ */
/*  Tapered limb geometry                                              */
/* ------------------------------------------------------------------ */

/**
 * A filled limb segment from (x1,y1) to (x2,y2), `w1` wide at the start
 * and `w2` at the end, with `bulge` extra half-width at the midpoint for
 * the muscle belly (bicep, calf, quad sweep).
 *
 * Both ends are rounded with cubic curves rather than arcs. An `A` command
 * needs large-arc and sweep flags whose correct values depend on the
 * segment's direction, and these segments point in every direction as the
 * solver poses them — one wrong flag inverts a cap into a spike. Cubics
 * have no flags, so the same expression is correct at every angle.
 */
function limb(
  x1: number,
  y1: number,
  w1: number,
  x2: number,
  y2: number,
  w2: number,
  bulge = 0,
): string {
  const dx = x2 - x1;
  const dy = y2 - y1;
  const len = Math.hypot(dx, dy) || 1;
  const ux = dx / len;
  const uy = dy / len;
  // Left-hand perpendicular.
  const px = -uy;
  const py = ux;

  const r1 = w1 / 2;
  const r2 = w2 / 2;
  const rm = (r1 + r2) / 2 + bulge;
  const mx = (x1 + x2) / 2;
  const my = (y1 + y2) / 2;

  // Cap control-point reach. 4/3·tan(π/8)·r ≈ 0.552r per quadrant, so a
  // half-circle drawn as one cubic wants about 1.33r.
  const c1 = r1 * 1.33;
  const c2 = r2 * 1.33;

  const p = (x: number, y: number) => `${x.toFixed(2)} ${y.toFixed(2)}`;

  return [
    `M${p(x1 + px * r1, y1 + py * r1)}`,
    `Q${p(mx + px * rm, my + py * rm)} ${p(x2 + px * r2, y2 + py * r2)}`,
    `C${p(x2 + px * r2 + ux * c2, y2 + py * r2 + uy * c2)} ${p(x2 - px * r2 + ux * c2, y2 - py * r2 + uy * c2)} ${p(x2 - px * r2, y2 - py * r2)}`,
    `Q${p(mx - px * rm, my - py * rm)} ${p(x1 - px * r1, y1 - py * r1)}`,
    `C${p(x1 - px * r1 - ux * c1, y1 - py * r1 - uy * c1)} ${p(x1 + px * r1 - ux * c1, y1 + py * r1 - uy * c1)} ${p(x1 + px * r1, y1 + py * r1)}`,
    "Z",
  ].join(" ");
}

/* ------------------------------------------------------------------ */
/*  Per-gender build                                                   */
/* ------------------------------------------------------------------ */

interface Build {
  /**
   * Where the LEFT upper arm is drawn from (the right mirrors about
   * x=180). Deliberately not the pivot.
   *
   * Both arms pivot at 180,68 — the centre of the chest — because that is
   * the rig the solver was built against. Drawing the arm from that point
   * meant its outer edge stayed inside the torso silhouette until y≈79,
   * so the arm appeared to grow out of the ribs rather than the shoulder,
   * which is the single thing that made the whole figure read as wrong.
   * Drawing it from the shoulder instead puts the deltoid where a deltoid
   * goes, and the arm clears the body at y≈73.
   *
   * The cost is that this root orbits the pivot as the arm rotates — but
   * it is only ~11px from it, and the torso is drawn over the arms, so
   * the root is under the chest at every angle the solver produces.
   */
  armRoot: [number, number];
  /** Segment widths: [start, end, bulge]. */
  upperArm: [number, number, number];
  foreArm: [number, number, number];
  thigh: [number, number, number];
  shin: [number, number, number];
  /** Torso silhouette, shoulders → waist → hip. */
  torso: string;
  /** Kit shape, clipped to the torso. */
  kit: string;
  /** Lower edge of the kit, for the trim band. */
  trimY: number;
  /** Top of the pelvis block. The gap between this and `trimY` is the
   *  exposed midriff — without it the vest and the shorts meet and the
   *  figure reads as wearing a one-piece with a belt. */
  pelvisY: number;
  /** How far down the thigh the shorts reach. */
  shortsTo: number;
  shortsW: [number, number];
}

