function Hair({ gender }: { gender: FigureGender }) {
  if (gender === "female") {
    return (
      <>
        <path
          d="M166.5 30 Q165 19 173 16 Q180 13.5 187 16 Q195 19 193.5 30 Q194.5 40 192.5 48 Q190.5 39 187 35.5 Q189 27 180 25.2 Q171 27 173 35.5 Q169.5 39 167.5 48 Q165.5 40 166.5 30 Z"
          fill={HAIR}
        />
        {/* Ponytail. Sits behind the head so a rotated pose never shows it
            clipping across the face. */}
        <path d="M191 31 Q203 36 200 50 Q197 42 189 38 Z" fill={HAIR} />
      </>
    );
  }
  if (gender === "male") {
    // A crop that actually covers the skull. The previous hair was a thin
    // rim across the crown, which left the head reading as bald with a
    // seam drawn on it.
    return (
      <path
        d="M167.4 32 Q166 22 173 18.5 Q180 15.5 187 18.5 Q194 22 192.6 32 Q191 27 186 25.5 Q180 24 174 25.5 Q169 27 167.4 32 Z"
        fill={HAIR}
      />
    );
  }
  return (
    <path
      d="M168 31 Q167 22 173.5 19 Q180 16.5 186.5 19 Q193 22 192 31 Q190 26.5 185.5 25.2 Q180 23.8 174.5 25.2 Q170 26.5 168 31 Z"
      fill={HAIR}
    />
  );
}

/** Front-view trainer. Authored at the ankle with the toe toward −x, then
 *  mirrored for the other foot, so both shoes splay outward. */
function Shoe({ x, dir, trim }: { x: number; dir: 1 | -1; trim: string }) {
  return (
    <g transform={`translate(${x} 177) scale(${dir} 1)`}>
      <path
        d="M-10.5 -3.5 Q-13 1 -12.5 5.5 Q-12 8.5 -8 8.5 L6 8.5 Q10 8.5 10 5 Q10 0.5 6.5 -2 Q2.5 -5 -2 -5 Q-7 -5 -10.5 -3.5 Z"
        fill={SHOE}
      />
      <path d="M-12.6 4 Q-12 8.5 -8 8.5 L6 8.5 Q10 8.5 10 5 Z" fill={trim} />
      <path d="M-4 -4.6 Q-1 0 1.5 5" stroke={SHOE_SHADE} strokeWidth={1.2} fill="none" strokeLinecap="round" />
    </g>
  );
}

/** A hand, not a circle. Slight taper into a mitt with a thumb notch. */
function Hand({ x, y, dir, fill }: { x: number; y: number; dir: 1 | -1; fill: string }) {
  return (
    <g transform={`translate(${x} ${y}) scale(${dir} 1) rotate(28)`}>
      <path
        d="M-4.5 -5.5 Q3 -6.5 6 -1.5 Q8.5 2.5 5.5 6 Q2 9.5 -2.5 8 Q-6.5 6.5 -7 1.5 Q-7.3 -3.5 -4.5 -5.5 Z"
        fill={fill}
      />
      <path d="M-6.5 -1.5 Q-9.5 0.5 -8 3.5" stroke={fill} strokeWidth={3.4} fill="none" strokeLinecap="round" />
    </g>
  );
}

/* ------------------------------------------------------------------ */

export default function HumanFigure({ gender = "male" }: { gender?: FigureGender }) {
  // `useId` is unique per component instance, which is what keeps a grid of
  // forty figures from all resolving `url(#skin)` to the first one's
  // gradient. The colons React puts in the id are not valid in a URL
  // fragment, hence the strip.
  const uid = useId().replace(/[^a-zA-Z0-9]/g, "");
  const gSkin = `sk${uid}`;
  const gKit = `kt${uid}`;
  const gTorso = `ts${uid}`;
  const clip = `tc${uid}`;

  const b = buildFor(gender);
  const trim = TRIM[gender];
  const skin = `url(#${gSkin})`;
  const kitFill = `url(#${gKit})`;

  const KNEE_L = { x: 162.5, y: 144.5 };
  const KNEE_R = { x: 197.5, y: 144.5 };
  const ELBOW_L = { x: 156, y: 81.5 };
  const ELBOW_R = { x: 204, y: 81.5 };

  return (
    <>
      <defs>
        {/* Across-the-body shading in each shape's own box, so every limb
            gets its own light side without a single global gradient that
            would break the moment a limb rotated. */}
        <linearGradient id={gSkin} x1="0" y1="0" x2="1" y2="0.4">
          <stop offset="0%" stopColor={SKIN.lit} />
          <stop offset="46%" stopColor={SKIN.base} />
          <stop offset="100%" stopColor={SKIN.shade} />
        </linearGradient>
        <linearGradient id={gKit} x1="0" y1="0" x2="1" y2="0.4">
          <stop offset="0%" stopColor={KIT.lit} />
          <stop offset="52%" stopColor={KIT.base} />
          <stop offset="100%" stopColor={KIT.shade} />
        </linearGradient>
        <linearGradient id={gTorso} x1="0.1" y1="0" x2="0.95" y2="0.6">
          <stop offset="0%" stopColor={SKIN.lit} />
          <stop offset="40%" stopColor={SKIN.base} />
          <stop offset="100%" stopColor={SKIN.shade} />
        </linearGradient>
        <clipPath id={clip}>
          <path d={b.torso} />
        </clipPath>
      </defs>

      {/* ---------------- Legs ---------------- */}
      {/* Drawn first so the pelvis and torso overlap them at the hip. */}
      <g className="motion-leg-l" style={{ transformOrigin: "180px 112px" }}>
        <path d={limb(180, 112, b.shortsW[0], 171, b.shortsTo, b.shortsW[1])} fill={kitFill} />
        <path
          d={limb(171, b.shortsTo - 4, b.thigh[0] * 0.78, KNEE_L.x, KNEE_L.y, b.thigh[1], b.thigh[2])}
          fill={skin}
        />
        <g className="motion-knee-l" style={{ transformOrigin: `${KNEE_L.x}px ${KNEE_L.y}px` }}>
          <path d={limb(KNEE_L.x, KNEE_L.y, b.shin[0], 145, 174, b.shin[1], b.shin[2])} fill={skin} />
          <Shoe x={145} dir={-1} trim={trim} />
        </g>
      </g>

      <g className="motion-leg-r" style={{ transformOrigin: "180px 112px" }}>
        <path d={limb(180, 112, b.shortsW[0], 189, b.shortsTo, b.shortsW[1])} fill={kitFill} />
        <path
          d={limb(189, b.shortsTo - 4, b.thigh[0] * 0.78, KNEE_R.x, KNEE_R.y, b.thigh[1], b.thigh[2])}
          fill={skin}
        />
        <g className="motion-knee-r" style={{ transformOrigin: `${KNEE_R.x}px ${KNEE_R.y}px` }}>
          <path d={limb(KNEE_R.x, KNEE_R.y, b.shin[0], 215, 174, b.shin[1], b.shin[2])} fill={skin} />
          <Shoe x={215} dir={1} trim={trim} />
        </g>
      </g>

      {/* ---------------- Upper body ----------------
          Arms, torso and head share the hip pivot so a push-up, plank or
          dip tilts them as one rigid piece. Rotating the torso on its own
          pivot leaves the head hanging where the shoulders used to be. */}
      <g className="motion-upper-body" style={{ transformOrigin: "180px 112px" }}>
        <g className="motion-arm-l" style={{ transformOrigin: "180px 68px" }}>
          <path
            d={limb(b.armRoot[0], b.armRoot[1], b.upperArm[0], ELBOW_L.x, ELBOW_L.y, b.upperArm[1], b.upperArm[2])}
            fill={skin}
          />
          <g className="motion-elbow-l" style={{ transformOrigin: `${ELBOW_L.x}px ${ELBOW_L.y}px` }}>
            <path
              d={limb(ELBOW_L.x, ELBOW_L.y, b.foreArm[0], 133, 94, b.foreArm[1], b.foreArm[2])}
              fill={skin}
            />
            <Hand x={132} y={95} dir={-1} fill={SKIN.base} />
          </g>
        </g>

        <g className="motion-arm-r" style={{ transformOrigin: "180px 68px" }}>
          <path
            d={limb(360 - b.armRoot[0], b.armRoot[1], b.upperArm[0], ELBOW_R.x, ELBOW_R.y, b.upperArm[1], b.upperArm[2])}
            fill={skin}
          />
          <g className="motion-elbow-r" style={{ transformOrigin: `${ELBOW_R.x}px ${ELBOW_R.y}px` }}>
            <path
              d={limb(ELBOW_R.x, ELBOW_R.y, b.foreArm[0], 227, 94, b.foreArm[1], b.foreArm[2])}
              fill={skin}
            />
            <Hand x={228} y={95} dir={1} fill={SKIN.base} />
          </g>
        </g>

        {/* Neck. Sits under the torso so the trapezius edge covers its base. */}
        <path d={limb(180, 44, 15, 180, 60, 17)} fill={SKIN.shade} />

        <g className="motion-torso">
          <path d={b.torso} fill={`url(#${gTorso})`} />

          <g clipPath={`url(#${clip})`}>
            <path d={b.kit} fill={kitFill} />

            {/* Pelvis block. Without it the two hip-anchored shorts shapes
                leave a visible notch at the crotch the moment a movement
                spreads the legs — jacks, sumo squats, skater hops. */}
            <rect x={146} y={b.pelvisY} width={68} height={20} fill={kitFill} />

            {/* The one accent on the body, and it sits on the waistband
                where a waistband actually is. An earlier version put it at
                the vest hem, which read as a belt worn across the chest. */}
            <rect x={146} y={b.pelvisY} width={68} height={2.5} fill={trim} opacity={0.85} />

            {/* Linea alba, in the exposed midriff only. Faint on purpose:
                at a 44px thumbnail anything stronger reads as a scar. */}
            <path
              d={`M180 ${b.trimY + 3} L180 ${b.pelvisY - 2}`}
              stroke={SKIN.shade}
              strokeWidth={1.1}
              strokeLinecap="round"
              fill="none"
              opacity={0.38}
            />

            {/* Core shadow down both flanks. Neutral black rather than a
                skin tone, because it has to sit over the kit as well. */}
            <g fill="#000" opacity={0.2}>
              <path d="M155 60 Q161 86 163 118 L153 118 L153 60 Z" />
              <path d="M205 60 Q199 86 197 118 L207 118 L207 60 Z" />
            </g>
          </g>

          {/* Silhouette edge. One hairline holds the body together against
              the dark card without reading as a line drawing. */}
          <path d={b.torso} fill="none" stroke={SKIN.shade} strokeWidth={1.1} opacity={0.45} />
        </g>

        <g className="motion-head">
          <circle cx={180} cy={36} r={13} fill={skin} />
          {/* Ear, on the shaded side only — two ears on a front-facing head
              at this scale read as lumps. */}
          <ellipse cx={192.5} cy={37} rx={2.6} ry={3.6} fill={SKIN.shade} opacity={0.75} />
          <Hair gender={gender} />
          <circle cx={180} cy={36} r={13} fill="none" stroke={SKIN.shade} strokeWidth={1.1} opacity={0.5} />
        </g>
      </g>
    </>
  );
}
