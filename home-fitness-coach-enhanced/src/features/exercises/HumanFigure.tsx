import { useId } from "react";

/**
 * The athlete.
 *
 * Every exercise demo in the app is this figure, posed by the solver in
 * `src/anim`. It is drawn entirely in vector, so all 39 catalogue
 * movements plus anything the AI invents cost zero download.
 *
 * ── What changed, and why it matters ──────────────────────────────────
 *
 * The previous figure was built from `<path>` elements with a uniform
 * `stroke-width`: a limb was a rod of constant thickness with a round cap.
 * That is why it read as a toy. Real limbs are tapered and have mass — a
 * thigh is roughly twice as thick at the hip as at the knee, a calf bulges
 * behind the shin, a deltoid caps the shoulder. None of that can be
 * expressed by a stroke.
 *
 * Every segment is now a FILLED, TAPERED path generated by `limb()` below,
 * with a per-shape gradient giving it volume. The head came down from r16
 * to r13 — at r16 the figure was five heads tall, which is a child's
 * proportions and the single loudest "cheap illustration" tell in the old
 * artwork.
 *
 * ── What deliberately did NOT change ──────────────────────────────────
 *
 * Every joint coordinate, group class name and transform-origin is
 * byte-identical to before, because `src/anim/rig.ts` measures its segment
 * lengths off this file and the renderer resolves these exact class names
 * once per mount:
 *
 *   hip 180,112 · shoulder 180,68 · head 180,36
 *   knee 162.5/197.5,144.5 · foot 145/215,177
 *   elbow 156/204,81.5 · hand 132/228,95
 *
 *   leg = <g motion-leg-*  (hip pivot)>      thigh → <g motion-knee-*>  shin+shoe
 *   arm = <g motion-arm-*  (shoulder pivot)> upper → <g motion-elbow-*> forearm+hand
 *
 * So this is a re-skin, not a re-rig: every solved pose, the IK grounding
 * and the whole `anim-check` harness keep working untouched.
 *
 * ── One honest limitation ─────────────────────────────────────────────
 *
 * Both arms pivot from 180,68 — the centre of the chest — rather than from
 * two separate shoulder sockets, because that is the rig the solver was
 * built against. The torso is therefore drawn OVER the upper arms, which
 * hides the shared pivot. It also means the figure cannot show a shoulder
 * girdle that shrugs or protracts.
 */

export type FigureGender = "male" | "female" | "neutral";

