#!/usr/bin/env node
/**
 * npm run clips            check exercise-clips/, write the ready list, print what is missing
 * npm run clips -- --migrate   copy the clips already bundled in public/videos into
 *                              exercise-clips/ under their new <id>.mp4 names first
 * npm run clips -- --dir some/folder
 *
 * Reads only src/data/exerciseClips.ts (the list of ids) and the files; needs no packages.
 * A file is "ready" when: name is <id>.mp4, size < 1,000,000 bytes, 5-8 seconds, H.264.
 */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const dirArg = args.includes("--dir") ? args[args.indexOf("--dir") + 1] : "exercise-clips";
const dir = path.resolve(root, dirArg);
const MAX_BYTES = 1_000_000, MIN_S = 5, MAX_S = 8;

const dataSrc = fs.readFileSync(path.join(root, "src/data/exerciseClips.ts"), "utf8");
const entries = [...dataSrc.matchAll(/^\s*\{ id: "([^"]+)", name: "([^"]+)"(?:, aliases: \[[^\]]*\])?(?:, from: "([^"]+)")? \}/gm)]
  .map((m) => ({ id: m[1], name: m[2], from: m[3] || "" }));
if (entries.length < 50) { console.error("Could not read the exercise list from src/data/exerciseClips.ts"); process.exit(1); }

const vidSrc = fs.readFileSync(path.join(root, "src/features/exercises/exerciseVideos.ts"), "utf8");
const legacy = Object.fromEntries([...vidSrc.matchAll(/^\s*"([^"]+)":\s*"\/videos\/([^"]+)"/gm)].map((m) => [m[1], m[2]]));

if (args.includes("--migrate")) {
  fs.mkdirSync(dir, { recursive: true });
  let n = 0;
  for (const e of entries) {
    const f = legacy[e.id];
    const from = f && path.join(root, "public/videos", f);
    const to = path.join(dir, `${e.id}.mp4`);
    if (from && fs.existsSync(from) && !fs.existsSync(to)) { fs.copyFileSync(from, to); n++; }
  }
  console.log(`Copied ${n} bundled clip(s) into ${path.relative(root, dir)}/ with their new names.\n`);
}

/** Reads length and layout from the mp4 header without any tool. */
function probe(file) {
  const fd = fs.openSync(file, "r");
  const size = fs.fstatSync(fd).size;
  let pos = 0, moovAt = -1, mdatAt = -1, seconds = 0, avc = false;
  const head = Buffer.alloc(16);
  const readBox = (start) => { fs.readSync(fd, head, 0, 16, start); let len = head.readUInt32BE(0); const type = head.toString("latin1", 4, 8); if (len === 1) len = Number(head.readBigUInt64BE(8)); return { len, type }; };
  while (pos + 8 <= size) {
    const { len, type } = readBox(pos);
    if (len < 8) break;
    if (type === "moov") {
      moovAt = pos;
      const buf = Buffer.alloc(Math.min(len, 4 * 1024 * 1024));
      fs.readSync(fd, buf, 0, buf.length, pos);
      const i = buf.indexOf("mvhd");
      if (i > 0) { const ver = buf[i + 4]; const ts = ver === 1 ? buf.readUInt32BE(i + 24) : buf.readUInt32BE(i + 16); const du = ver === 1 ? Number(buf.readBigUInt64BE(i + 28)) : buf.readUInt32BE(i + 20); if (ts) seconds = du / ts; }
      avc = buf.includes("avc1") || buf.includes("avc3");
    }
    if (type === "mdat") mdatAt = pos;
    pos += len;
  }
  fs.closeSync(fd);
  return { size, seconds, avc, faststart: moovAt >= 0 && (mdatAt < 0 || moovAt < mdatAt) };
}

fs.mkdirSync(dir, { recursive: true });
const ids = new Set(entries.map((e) => e.id));
const files = fs.readdirSync(dir).filter((f) => !f.startsWith("."));
const ready = {}, problems = [], unknown = [];
for (const f of files) {
  const id = f.replace(/\.mp4$/, "");
  if (!f.endsWith(".mp4") || !ids.has(id)) { unknown.push(f); continue; }
  const full = path.join(dir, f);
  let p;
  try { p = probe(full); } catch { problems.push([id, "cannot read as mp4"]); continue; }
  const bad = [];
  if (p.size >= MAX_BYTES) bad.push(`${(p.size / 1e6).toFixed(2)} MB (must be under 1 MB)`);
  if (!p.seconds) bad.push("length unreadable");
  else if (p.seconds < MIN_S - 0.2 || p.seconds > MAX_S + 0.2) bad.push(`${p.seconds.toFixed(1)} s (must be 5-8 s)`);
  if (!p.avc) bad.push("not H.264");
  if (bad.length) { problems.push([id, bad.join(", ")]); continue; }
  const h = crypto.createHash("sha1").update(fs.readFileSync(full)).digest("hex").slice(0, 8);
  ready[id] = { h, b: p.size, s: Math.round(p.seconds * 10) / 10 };
  if (!p.faststart) problems.push([id, "OK but not 'faststart' (slower to start); re-encode with -movflags +faststart"]);
}

const out = `/* GENERATED by \`npm run clips\`. Do not edit by hand.
 * An id appears here only after its file in exercise-clips/ passed the checks
 * (name, size, length). h = short content hash, b = bytes, s = seconds. */
export const READY_CLIPS: Record<string, { h: string; b: number; s: number }> = ${JSON.stringify(ready, null, 2)};
`;
fs.writeFileSync(path.join(root, "src/data/exerciseClips.generated.ts"), out);

const missing = entries.filter((e) => !ready[e.id]);
const noClipAtAll = missing.filter((e) => e.from);
console.log(`Checked ${files.length} file(s) in ${path.relative(root, dir)}/`);
console.log(`READY: ${Object.keys(ready).length} of ${entries.length}\n`);
if (problems.length) { console.log("NEEDS FIXING:"); for (const [id, why] of problems) console.log(`  ${id}.mp4  ->  ${why}`); console.log(""); }
if (unknown.length) { console.log("IGNORED (name is not <id>.mp4 for a known exercise):"); for (const f of unknown) console.log(`  ${f}`); console.log(""); }
const todo = missing.filter((e) => !problems.some(([id]) => id === e.id));
console.log(`STILL MISSING (${todo.length}) - give each clip exactly this file name:`);
for (const e of todo) console.log(`  ${(e.id + ".mp4").padEnd(46)} ${e.name}${e.from ? `   [${e.from}; no clip anywhere yet]` : ""}`);
console.log(`\n${noClipAtAll.length} exercise(s) have no clip anywhere (marked above). The rest have an older bundled clip that still plays until the Storage one is ready.`);
console.log(`\nShrink / trim any clip that failed (5-8 s, silent, small):\n  ffmpeg -i IN.mp4 -t 8 -an -vf "scale=-2:480,fps=24" -c:v libx264 -crf 28 -preset veryfast -movflags +faststart exercise-clips/<id>.mp4`);
if (Object.keys(ready).length) {
  console.log(`\nUpload the ready clips, then rebuild the app:\n  gsutil -m -h "Cache-Control:public,max-age=31536000,immutable" -h "Content-Type:video/mp4" cp ${path.relative(root, dir)}/*.mp4 gs://fitness-app-1e5f0.firebasestorage.app/exercise-demos/`);
}
