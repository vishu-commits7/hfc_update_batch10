#!/usr/bin/env node
/**
 * npm run i18n:check
 * - every English key has a Hindi line, and Hindi has no stray keys
 * - {placeholders} match between English and Hindi
 * - every t("key") used in src exists in en.ts
 * - writes HINDI_REVIEW.md: the Hindi lines flagged for a native speaker
 * Uses the TypeScript compiler already in node_modules; installs nothing.
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const ts = require(path.join(root, "node_modules/typescript"));
const out = fs.mkdtempSync(path.join(os.tmpdir(), "i18n-check-"));
for (const f of ["en", "hi"]) {
  const src = fs.readFileSync(path.join(root, "src/i18n", `${f}.ts`), "utf8");
  fs.writeFileSync(path.join(out, `${f}.js`), ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText);
}
const { en } = require(path.join(out, "en.js"));
const { hi, REVIEW } = require(path.join(out, "hi.js"));
fs.rmSync(out, { recursive: true, force: true });

let bad = 0;
const fail = (m) => { bad++; console.log("ERROR " + m); };
const ph = (s) => (s.match(/\{\w+\}/g) || []).sort().join(",");
for (const k of Object.keys(en)) {
  if (!(k in hi)) { fail(`missing Hindi: ${k}`); continue; }
  if (ph(en[k]) !== ph(hi[k])) fail(`placeholders differ: ${k}  en[${ph(en[k])}] hi[${ph(hi[k])}]`);
  if (!hi[k].trim()) fail(`empty Hindi: ${k}`);
}
for (const k of Object.keys(hi)) if (!(k in en)) fail(`Hindi key not in English: ${k}`);
for (const k of Object.keys(REVIEW || {})) if (!(k in en)) fail(`REVIEW key not in English: ${k}`);

// keys used in code
const used = new Set();
const walk = (d) => {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) { if (e.name !== "i18n") walk(p); continue; }
    if (!/\.(ts|tsx)$/.test(e.name)) continue;
    const s = fs.readFileSync(p, "utf8");
    for (const m of s.matchAll(/\b(?:t|tr|tSplit)\(\s*"([a-zA-Z0-9_.]+)"/g)) {
      used.add(m[1]);
      if (!(m[1] in en)) fail(`unknown key "${m[1]}" used in ${path.relative(root, p)}`);
    }
  }
};
walk(path.join(root, "src"));
// keys built from a template (t(`goal.${x}.label`)) are matched by prefix
const dynamic = ["goal.", "level.", "equip.", "area.", "set.theme.", "arena.tab.", "gs.h", "gs.s"];
const unused = Object.keys(en).filter(k => !used.has(k) && !dynamic.some(p => k.startsWith(p)));

const review = Object.entries(REVIEW || {});
const md = ["# Hindi lines for a native-speaker review", "",
  "Generated by `npm run i18n:check` from `src/i18n/hi.ts` (REVIEW). Please confirm or correct each line, then edit `hi.ts` and remove it from REVIEW.", "",
  "| Key | English | Hindi now | What to check |", "|---|---|---|---|",
  ...review.map(([k, why]) => `| \`${k}\` | ${en[k].replace(/\|/g, "\\|")} | ${hi[k].replace(/\|/g, "\\|")} | ${String(why).replace(/\|/g, "\\|")} |`),
  "", "## Not translated (stay in English)", "",
  "- Privacy Policy and Terms of Service text (needs a legal translator).",
  "- Spoken voice-coaching lines (device voice is set to English).",
  "- Exercise names, coaching tips, exercise descriptions, program text.",
  "- Server-written text: quest titles, plan reasons, league names, trophy names.",
  "- Screens beyond the six covered here (community, reels, friends, paywall, and the Arena tab contents).",
  ""];
fs.writeFileSync(path.join(root, "HINDI_REVIEW.md"), md.join("\n"));

console.log(`${Object.keys(en).length} English keys, ${Object.keys(hi).length} Hindi lines, ${review.length} flagged for review (see HINDI_REVIEW.md)`);
if (unused.length) console.log(`NOTE  ${unused.length} keys not used by a literal t("...") call: ${unused.slice(0, 12).join(", ")}${unused.length > 12 ? ", ..." : ""}`);
console.log(bad ? `\n${bad} problem(s).` : "\nAll translations OK.");
process.exit(bad ? 1 : 0);
